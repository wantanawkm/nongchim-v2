export function formatThaiDateBE(isoDate: string): string {
  if (!isoDate) return '-';
  const parts = isoDate.split('-');
  if (parts.length !== 3) return isoDate;
  const yearCE = parseInt(parts[0], 10);
  const monthIdx = parseInt(parts[1], 10) - 1;
  const day = parseInt(parts[2], 10);
  if (isNaN(yearCE) || monthIdx < 0 || monthIdx > 11 || isNaN(day)) return isoDate;
  const yearBE = yearCE + 543;
  return `${day} ${THAI_SHORT_MONTHS[monthIdx]} ${yearBE}`;
}

export function getTodayIsoDate(): string {
  const now = new Date();
  const y = now.getFullYear();
  const m = String(now.getMonth() + 1).padStart(2, '0');
  const d = String(now.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

export function addDaysToIsoDate(baseIso: string, daysToAdd: number): string {
  const d = baseIso ? new Date(`${baseIso}T00:00:00`) : new Date();
  d.setDate(d.getDate() + daysToAdd);
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${y}-${m}-${day}`;
}

export function calculateBmi(weightKg: number, heightCm: number): number {
  if (!weightKg || !heightCm || heightCm <= 0) return 0;
  const hMeters = heightCm / 100;
  return Number((weightKg / (hMeters * hMeters)).toFixed(1));
}

export function interpretBmi(bmi: number): {
  label: string;
  shortLabel: string;
  tone: 'emerald' | 'amber' | 'rose' | 'sky';
} {
  if (!bmi || bmi <= 0) {
    return { label: 'รอคำนวณ', shortLabel: '-', tone: 'sky' };
  }
  if (bmi < 18.5) {
    return { label: 'ผอม / น้ำหนักต่ำกว่าเกณฑ์', shortLabel: 'ผอม', tone: 'sky' };
  }
  if (bmi < 23.0) {
    return { label: 'สมส่วน (เกณฑ์ปกติ)', shortLabel: 'สมส่วน', tone: 'emerald' };
  }
  if (bmi < 25.0) {
    return { label: 'ท้วม (น้ำหนักเกิน)', shortLabel: 'ท้วม', tone: 'amber' };
  }
  if (bmi < 30.0) {
    return { label: 'อ้วนระดับ 1 (เสี่ยงโรคเมตาบอลิก)', shortLabel: 'อ้วนระดับ 1', tone: 'rose' };
  }
  return { label: 'อ้วนระดับ 2 (อ้วนมาก)', shortLabel: 'อ้วนมาก', tone: 'rose' };
}

export function evaluateControlStatus(
  diseaseGroup: DiseaseGroup,
  systolic: number,
  diastolic: number,
  dtx: number,
  nextAppointmentDate?: string
): ControlStatus {
  const todayIso = getTodayIsoDate();
  if (nextAppointmentDate && nextAppointmentDate < todayIso) {
    return 'ขาดนัด';
  }

  const bpGood = systolic < 140 && diastolic < 90;
  const bpWatch = systolic >= 140 && systolic < 160 && diastolic < 100;

  const dmGood = dtx >= 70 && dtx <= 130;
  const dmWatch = dtx > 130 && dtx < 180;

  if (diseaseGroup === 'HT') {
    if (bpGood) return 'คุมได้ดี';
    if (bpWatch) return 'เฝ้าระวัง';
    return 'คุมไม่ได้';
  }

  if (diseaseGroup === 'DM') {
    if (dmGood) return 'คุมได้ดี';
    if (dmWatch) return 'เฝ้าระวัง';
    return 'คุมไม่ได้';
  }

  // DM+HT
  if (bpGood && dmGood) return 'คุมได้ดี';
  if (systolic >= 160 || diastolic >= 100 || dtx >= 180 || dtx < 70) return 'คุมไม่ได้';
  return 'เฝ้าระวัง';
}

